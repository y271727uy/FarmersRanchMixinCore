package com.y271727uy.FRMC.integration.acceleratedrendering;

import com.github.argon4w.acceleratedrendering.core.buffers.accelerated.builders.AcceleratedBufferBuilder;
import com.github.argon4w.acceleratedrendering.core.meshes.ServerMesh;
import com.github.argon4w.acceleratedrendering.core.programs.dispatchers.TransformProgramDispatcher;
import com.github.argon4w.acceleratedrendering.core.programs.dispatchers.meshes.MeshUploadingProgramDispatcher;
import com.github.argon4w.acceleratedrendering.core.utils.ByteBufferBuilder;
import com.github.argon4w.acceleratedrendering.core.utils.RenderTypeUtils;
import com.mojang.blaze3d.vertex.DefaultVertexFormat;
import com.mojang.blaze3d.vertex.VertexFormat;
import com.mojang.logging.LogUtils;
import com.y271727uy.FRMC.integration.citadel.render.ar.CitadelGpuPoseProgram;
import com.y271727uy.FRMC.integration.oculus.OculusIntegration;
import java.io.IOException;
import java.util.IdentityHashMap;
import java.util.Map;
import net.irisshaders.batchedentityrendering.impl.WrappableRenderType;
import net.irisshaders.iris.vertices.IrisVertexFormats;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.resources.ResourceLocation;
import org.lwjgl.system.MemoryUtil;
import org.slf4j.Logger;

import static org.lwjgl.opengl.GL45C.*;

public final class ArModelMeshUpload {
    public static final int VERTEX_BYTES = 36;
    private static final int OVERLAY_OFFSET = 24;
    private static final Logger LOGGER = LogUtils.getLogger();
    private static final Map<ServerMesh, Upload> UPLOADS = new IdentityHashMap<>();
    private static boolean hookActive;

    private ArModelMeshUpload() {}

    public static Format formatFor(AcceleratedBufferBuilder builder) {
        return formatFor(builder, false);
    }

    public static Format formatFor(AcceleratedBufferBuilder builder, boolean allowTranslucent) {
        if (!hookActive || builder.getMode() != VertexFormat.Mode.QUADS
                || unwrap(builder.getRenderType()).format() != DefaultVertexFormat.NEW_ENTITY
                || (!allowTranslucent && RenderTypeUtils.isTranslucent(builder.getRenderType()))) {
            return null;
        }
        var override = builder.getProgramOverride();
        if (override.overrideId() != 0 || override.getVaryingSize() != 16
                || override.uploading().getClass() != MeshUploadingProgramDispatcher.Default.class
                || override.transform().getClass() != TransformProgramDispatcher.Default.class) {
            return null;
        }
        var layout = builder.getLayout();
        if (builder.getVertexSize() != layout.getSize()) {
            return null;
        }
        if (layout.getSize() == VERTEX_BYTES && override.getMeshInfoSize() == 28) {
            return Format.VANILLA;
        }
        if (layout.getSize() == 56 && override.getMeshInfoSize() == 36 && OculusIntegration.IS_IRIS_INSTALLED
                && layout.getElementOffset(IrisVertexFormats.ENTITY_ID_ELEMENT) == 36
                && layout.getElementOffset(IrisVertexFormats.MID_TEXTURE_ELEMENT) == 44
                && layout.getElementOffset(IrisVertexFormats.TANGENT_ELEMENT) == 52) {
            return Format.IRIS;
        }
        return null;
    }

    public static boolean isCutout(RenderType material) {
        material = unwrap(material);
        ResourceLocation texture = RenderTypeUtils.getTextureLocation(material);
        return texture != null && (material == RenderType.entityCutout(texture)
                || material == RenderType.entityCutoutNoCull(texture, true)
                || material == RenderType.entityCutoutNoCull(texture, false));
    }

    public static RenderType unwrap(RenderType material) {
        if (OculusIntegration.IS_IRIS_INSTALLED) {
            while (material instanceof WrappableRenderType wrapper) {
                material = wrapper.unwrap();
            }
        }
        return material;
    }

    public static long appendVertices(ByteBufferBuilder target, long source, int count, Format format, int poseTag) {
        long destination = target.reserve(count * VERTEX_BYTES);
        if (format == Format.VANILLA) {
            MemoryUtil.memCopy(source, destination, (long) count * VERTEX_BYTES);
        }
        for (int vertex = 0; vertex < count; vertex++) {
            long address = destination + (long) vertex * VERTEX_BYTES;
            if (format == Format.IRIS) {
                // Extended attributes are generated by AR per submission, never stored in the mesh.
                MemoryUtil.memCopy(source + (long) vertex * format.vertexBytes, address, VERTEX_BYTES);
            }
            MemoryUtil.memPutInt(address + OVERLAY_OFFSET, poseTag);
        }
        return destination;
    }

    public static void activate() {
        hookActive = true;
    }

    public static void register(ServerMesh mesh, Format format, PostUpload postUpload) {
        UPLOADS.put(mesh, new Upload(format, postUpload));
    }

    public static boolean handles(ServerMesh mesh) {
        return UPLOADS.containsKey(mesh);
    }

    public static int dispatch(ServerMesh mesh, int count, int vertices, int offset) {
        Upload upload = UPLOADS.get(mesh);
        int previous = glGetInteger(GL_CURRENT_PROGRAM);
        try {
            glUseProgram(upload.format.program);
            glUniform1ui(0, count);
            glUniform1ui(1, vertices);
            glUniform1ui(2, offset);
            glDispatchCompute((count * vertices + 127) / 128, 1, 1);
            boolean culled = upload.postUpload != null && upload.postUpload.dispatch(count, vertices, offset);
            return GL_SHADER_STORAGE_BARRIER_BIT | (culled ? GL_VERTEX_ATTRIB_ARRAY_BARRIER_BIT : 0);
        } finally {
            glUseProgram(previous);
        }
    }

    public static void release() {
        UPLOADS.clear();
        for (Format format : Format.values()) {
            if (format.program != 0) {
                glDeleteProgram(format.program);
                format.program = 0;
            }
        }
    }

    public enum Format {
        VANILLA(VERTEX_BYTES),
        IRIS(56);

        public final int vertexBytes;
        private int program;
        private boolean unavailable;

        Format(int vertexBytes) {
            this.vertexBytes = vertexBytes;
        }

        public boolean initialize() {
            if (!unavailable && program == 0) {
                try {
                    program = CitadelGpuPoseProgram.compileProgram("citadel_model_upload.comp",
                            this == IRIS ? "#define IRIS_ENTITY\n" : "");
                } catch (IOException | RuntimeException exception) {
                    unavailable = true;
                    LOGGER.warn("[FRMC/AR] Whole-model upload unavailable for {}", this, exception);
                }
            }
            return !unavailable;
        }
    }

    public interface PostUpload {
        boolean dispatch(int count, int vertices, int offset);
    }

    private record Upload(Format format, PostUpload postUpload) {}
}
